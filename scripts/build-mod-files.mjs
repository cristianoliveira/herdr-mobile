// Generates what the app embeds as strings:
// - src/mods/runtime.generated.ts: the mod runtime (src/mods/runtime/*.js) each engine loads.
// - src/definition/defaults.generated.ts: the shipped home (src/definition/defaults/),
//   plus check.mjs, bundled with esbuild from src/check/cli.ts.
// Runs on postinstall and before tests and typecheck.
import { build } from "esbuild";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const runtimeDir = join(root, "src/mods/runtime");
const runtime = {};
for (const name of readdirSync(runtimeDir).sort()) {
  if (name.endsWith(".js")) runtime[name.slice(0, -3)] = readFileSync(join(runtimeDir, name), "utf8");
}
writeFileSync(
  join(root, "src/mods/runtime.generated.ts"),
  `// Generated by scripts/build-mod-files.mjs. Do not edit.\nexport const RUNTIME_FILES: Record<string, string> = ${JSON.stringify(runtime, null, 2)};\n`,
);

const check = await build({
  entryPoints: [join(root, "src/check/cli.ts")],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node18",
  loader: { ".wasm": "binary" },
  write: false,
  legalComments: "none",
  banner: { js: "// check.mjs: checks the herdr-mobile home it sits in. Written by the app on every connect.\n// Run: node check.mjs [mod names...]\nimport { createRequire as __herdrRequire } from 'node:module'; const require = __herdrRequire(import.meta.url);" },
});

const defaultsDir = join(root, "src/definition/defaults");
const defaults = {};
const walk = (dir) => {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else defaults[relative(defaultsDir, full).split(sep).join("/")] = readFileSync(full, "utf8");
  }
};
walk(defaultsDir);
defaults["check.mjs"] = check.outputFiles[0].text;
writeFileSync(
  join(root, "src/definition/defaults.generated.ts"),
  `// Generated by scripts/build-mod-files.mjs. Do not edit.\nexport const DEFAULT_FILES: Record<string, string> = ${JSON.stringify(defaults)};\n`,
);
